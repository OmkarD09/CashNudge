"""Gemma LLM provider integration for payment reminder follow-up drafting."""

from abc import ABC, abstractmethod
from typing import Optional, List, Dict, Any
import httpx

from backend.config import settings
from backend.schemas import (
    FollowupDraftRequest,
    FollowupDraftResponse,
    FollowupTone,
)
from backend.prompt_builder import build_gemma_prompt
from backend.date_utils import compute_invoice_date_facts


class GemmaError(Exception):
    """Base exception for Gemma provider operations."""
    pass


class GemmaConnectionError(GemmaError):
    """Raised when connection to the Gemma provider service fails."""
    pass


class GemmaModelNotFoundError(GemmaError):
    """Raised when the requested Gemma model is not installed or available on the host."""
    pass


class GemmaTimeoutError(GemmaError):
    """Raised when a Gemma generation request times out."""
    pass


class GemmaConfigurationError(GemmaError):
    """Raised when credentials or configuration parameters are missing or invalid."""
    pass


class GemmaRateLimitError(GemmaError):
    """Raised when the hosted or local Gemma provider rate limit is exceeded (HTTP 429)."""
    pass


class GemmaResponseError(GemmaError):
    """Raised when the Gemma provider returns a malformed response."""
    pass


class BaseGemmaProvider(ABC):
    """Abstract interface for Gemma follow-up generation."""

    @abstractmethod
    def generate_followup(self, request: FollowupDraftRequest) -> FollowupDraftResponse:
        """Generate a drafted follow-up reminder based on factual invoice context."""
        pass

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Identifiable name of the model provider."""
        pass


class MockGemmaProvider(BaseGemmaProvider):
    """Deterministic mock provider for automated unit tests and development."""

    def __init__(self, override_draft: Optional[str] = None):
        self._override_draft = override_draft

    def generate_followup(self, request: FollowupDraftRequest) -> FollowupDraftResponse:
        date_facts = compute_invoice_date_facts(
            due_date=request.due_date,
            reference_date=request.reference_date,
            explicit_days_overdue=request.days_overdue,
        )

        if self._override_draft is not None:
            draft = self._override_draft
        else:
            draft = self._create_deterministic_draft(request, date_facts)

        warnings = [
            "Generated using Mock Gemma provider for development and testing. Output was not generated by a real neural language model."
        ]

        return FollowupDraftResponse(
            invoice_id=request.invoice_id,
            customer_name=request.customer_name,
            tone=request.tone,
            drafted_message=draft,
            inference_provider=self.provider_name,
            warnings=warnings,
            human_approval_required=True,
            date_facts=date_facts.model_dump(),
            metadata={
                "is_mock": True,
                "model": "mock-deterministic-v1",
            },
        )

    def _create_deterministic_draft(self, req: FollowupDraftRequest, facts) -> str:
        sender = req.business_name or "our team"
        amt_str = f" {req.currency} {req.invoice_amount:,.2f}" if req.invoice_amount is not None else ""
        
        if req.tone == FollowupTone.GENTLE:
            if facts.status == "upcoming":
                timing_str = f", which is scheduled for payment on {facts.due_date} (upcoming in {facts.days_until_due} day(s))"
            elif facts.status == "due_today":
                timing_str = f", which is due today ({facts.due_date})"
            elif facts.status == "overdue":
                timing_str = f", which was due on {facts.due_date} and is currently {facts.days_overdue} day(s) past due"
            else:
                timing_str = ""

            return (
                f"Subject: Friendly check-in regarding Invoice #{req.invoice_id}\n\n"
                f"Hi {req.customer_name},\n\n"
                f"I hope you are having a productive week.\n\n"
                f"This is a quick, friendly check-in regarding invoice #{req.invoice_id}{amt_str}{timing_str}. "
                f"Please let me know if you received the invoice or if you need any additional project details or paperwork from my side.\n\n"
                f"Thank you for your partnership,\n"
                f"{sender}"
            )
        else:  # FollowupTone.FIRM
            if facts.status == "overdue":
                overdue_str = f" is now {facts.days_overdue} day(s) past the agreed due date ({facts.due_date or 'prior terms'})"
            elif facts.status == "due_today":
                overdue_str = f" is due today ({facts.due_date})"
            elif facts.status == "upcoming":
                overdue_str = f" is scheduled for payment on {facts.due_date}"
            else:
                overdue_str = " remains outstanding"

            terms_str = f" (agreed terms: Net {req.payment_terms_days} days)" if req.payment_terms_days else ""
            return (
                f"Subject: Outstanding balance notice: Invoice #{req.invoice_id}\n\n"
                f"Dear {req.customer_name},\n\n"
                f"I am writing to follow up on invoice #{req.invoice_id}{amt_str}{terms_str}, which{overdue_str}.\n\n"
                f"Could you please confirm the current payment processing status and advise when we can expect the balance to be settled?\n\n"
                f"Thank you for your prompt attention to this matter.\n\n"
                f"Best regards,\n"
                f"{sender}"
            )


    @property
    def provider_name(self) -> str:
        return "MockGemmaProvider (Deterministic Development/Test)"


class OllamaGemmaProvider(BaseGemmaProvider):
    """Local Ollama-backed Gemma inference client."""

    def __init__(
        self,
        base_url: Optional[str] = None,
        model: Optional[str] = None,
        timeout: Optional[float] = None,
    ):
        self.base_url = (base_url or settings.ollama_base_url).rstrip("/")
        self.model = model or settings.ollama_model
        self.timeout = timeout if timeout is not None else settings.ollama_timeout_seconds

    def generate_followup(self, request: FollowupDraftRequest) -> FollowupDraftResponse:
        prompt = build_gemma_prompt(request)
        payload = {
            "model": self.model,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": 0.2,
            },
        }

        try:
            with httpx.Client(timeout=self.timeout) as client:
                resp = client.post(f"{self.base_url}/api/generate", json=payload)
        except httpx.ConnectError as e:
            raise GemmaConnectionError(
                f"Unable to connect to Ollama at {self.base_url}. "
                f"Ensure Ollama is installed and running ('ollama serve'). Details: {str(e)}"
            ) from e
        except httpx.TimeoutException as e:
            raise GemmaTimeoutError(
                f"Ollama inference timed out after {self.timeout} seconds for model '{self.model}'. "
                f"Consider increasing OLLAMA_TIMEOUT_SECONDS or using a lighter model. Details: {str(e)}"
            ) from e
        except Exception as e:
            raise GemmaError(f"Unexpected connection failure contacting Ollama: {str(e)}") from e

        if resp.status_code == 404:
            raise GemmaModelNotFoundError(
                f"Gemma model '{self.model}' was not found on the local Ollama instance at {self.base_url}. "
                f"Run 'ollama pull {self.model}' in your terminal to install it."
            )
        elif resp.status_code != 200:
            raise GemmaResponseError(
                f"Ollama returned HTTP error status {resp.status_code}: {resp.text}"
            )

        try:
            data = resp.json()
            raw_text = data.get("response", "").strip()
        except Exception as e:
            raise GemmaResponseError(f"Failed to parse JSON response from Ollama: {str(e)}") from e

        if not raw_text:
            raise GemmaResponseError("Ollama returned an empty response.")

        date_facts = compute_invoice_date_facts(
            due_date=request.due_date,
            reference_date=request.reference_date,
            explicit_days_overdue=request.days_overdue,
        )

        return FollowupDraftResponse(
            invoice_id=request.invoice_id,
            customer_name=request.customer_name,
            tone=request.tone,
            drafted_message=raw_text,
            inference_provider=self.provider_name,
            warnings=[
                "Drafted by local Gemma via Ollama. Review and edit before sending to client."
            ],
            human_approval_required=True,
            date_facts=date_facts.model_dump(),
            metadata={
                "model": self.model,
                "base_url": self.base_url,
                "eval_duration_ms": data.get("eval_duration"),
            },
        )

    @property
    def provider_name(self) -> str:
        return f"Gemma (Ollama: {self.model})"


class HostedGemmaProvider(BaseGemmaProvider):
    """OpenAI-compatible hosted API provider for Gemma (e.g. Groq, OpenRouter, Together)."""

    def __init__(
        self,
        base_url: Optional[str] = None,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
        timeout: float = 30.0,
    ):
        self.base_url = (base_url or settings.gemma_hosted_base_url or "").rstrip("/")
        self.api_key = api_key or settings.gemma_hosted_api_key
        self.model = model or settings.gemma_hosted_model
        self.timeout = timeout

        if not self.base_url:
            raise GemmaConfigurationError(
                "Missing GEMMA_HOSTED_BASE_URL. Specify the OpenAI-compatible endpoint URL in .env."
            )
        if not self.api_key:
            raise GemmaConfigurationError(
                "Missing GEMMA_HOSTED_API_KEY. Specify your hosted API key in .env."
            )

    def generate_followup(self, request: FollowupDraftRequest) -> FollowupDraftResponse:
        prompt = build_gemma_prompt(request)
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
            "HTTP-Referer": "http://localhost:8000",
            "X-Title": "CashNudge",
        }
        payload = {
            "model": self.model,
            "messages": [
                {"role": "user", "content": prompt}
            ],
            "temperature": 0.2,
        }

        try:
            with httpx.Client(timeout=self.timeout) as client:
                resp = client.post(f"{self.base_url}/chat/completions", headers=headers, json=payload)
        except httpx.ConnectError as e:
            raise GemmaConnectionError(
                f"Failed to connect to hosted Gemma endpoint at {self.base_url}: {str(e)}"
            ) from e
        except httpx.TimeoutException as e:
            raise GemmaTimeoutError(
                f"Hosted Gemma API request timed out after {self.timeout}s: {str(e)}"
            ) from e
        except Exception as e:
            raise GemmaError(f"Error calling hosted Gemma endpoint: {str(e)}") from e

        if resp.status_code in (401, 403):
            raise GemmaConfigurationError(
                f"Authentication failed for hosted Gemma endpoint at {self.base_url}. Verify GEMMA_HOSTED_API_KEY."
            )
        elif resp.status_code == 429:
            raise GemmaRateLimitError(
                f"Rate limit exceeded for hosted Gemma endpoint ({self.model}). Please try again later. Details: {resp.text}"
            )
        elif resp.status_code == 404:
            raise GemmaModelNotFoundError(
                f"Hosted Gemma model '{self.model}' was not found at {self.base_url}. Verify the model identifier."
            )
        elif resp.status_code != 200:
            raise GemmaResponseError(
                f"Hosted Gemma endpoint returned HTTP status {resp.status_code}: {resp.text}"
            )

        try:
            data = resp.json()
            raw_text = data["choices"][0]["message"]["content"].strip()
        except Exception as e:
            raise GemmaResponseError(f"Malformed response structure from hosted Gemma: {str(e)}") from e

        date_facts = compute_invoice_date_facts(
            due_date=request.due_date,
            reference_date=request.reference_date,
            explicit_days_overdue=request.days_overdue,
        )

        return FollowupDraftResponse(
            invoice_id=request.invoice_id,
            customer_name=request.customer_name,
            tone=request.tone,
            drafted_message=raw_text,
            inference_provider=self.provider_name,
            warnings=[
                "Drafted by hosted Gemma API. Prompt details transmitted to configured external endpoint. Always review before sending."
            ],
            human_approval_required=True,
            date_facts=date_facts.model_dump(),
            metadata={
                "model": self.model,
                "base_url": self.base_url,
            },
        )

    @property
    def provider_name(self) -> str:
        return f"Gemma (Hosted: {self.model})"


def get_gemma_provider(provider_type: Optional[str] = None) -> BaseGemmaProvider:
    """Factory to retrieve configured Gemma provider.
    
    Args:
        provider_type: 'mock', 'ollama', 'hosted', or None (uses GEMMA_PROVIDER setting).
    """
    mode = (provider_type or settings.gemma_provider).lower().strip()

    if mode == "ollama":
        return OllamaGemmaProvider()
    elif mode == "hosted":
        return HostedGemmaProvider()
    elif mode == "mock":
        return MockGemmaProvider()
    else:
        # Default explicit mock fallback when unrecognized
        return MockGemmaProvider()
